    /// The names of the functions of a scan, in source order.
    fn names(scan: &Scan) -> Vec<&str> {
        scan.functions
            .iter()
            .map(|(name, _)| name.as_str())
            .collect()
    }

    /// The entries of a set, in order.
    fn list(set: &BTreeSet<String>) -> Vec<&str> {
        set.iter().map(String::as_str).collect()
    }

    /// The production root [`LIB`] and the further `roots`.
    fn roots(further: &[(&str, bool)]) -> Vec<(String, bool)> {
        let roots = [(LIB, true)].into_iter().chain(further.iter().copied());
        roots
            .map(|(root, production)| (root.to_string(), production))
            .collect()
    }

    /// The inventory of `files`, with the production root [`LIB`] and the
    /// further roots, and its problems.
    fn inventory_of(files: &[(&str, &str)], further: &[(&str, bool)]) -> (Inventory, Vec<String>) {
        let (inventory, problems) =
            inventory(&Tree::from_files(files), &roots(further), LAYOUT.kernel);
        (inventory, problems.into_iter().collect())
    }

    /// A tree of `files` with empty registries and, unless `files` holds
    /// one, the `verification/open.json` that its contracts give.
    fn tree(files: &[(&str, &str)]) -> Tree {
        let mut tree =
            Tree::from_files(&[(LAYOUT.registry, NO_TARGETS), (LAYOUT.models, NO_MODELS)]);
        tree.insert(
            LAYOUT.axioms,
            repo::Entry::File(NO_AXIOMS.as_bytes().to_vec()),
        );
        for (path, text) in files {
            tree.insert(path, repo::Entry::File(text.as_bytes().to_vec()));
        }
        if !tree.exists(LAYOUT.open) {
            let open = open_json(&obligations(&tree, LAYOUT.kernel).0);
            tree.insert(LAYOUT.open, repo::Entry::File(open.into_bytes()));
        }
        tree
    }

    /// The problems of the check of [`tree`] of `files`, with the root
    /// [`LIB`].
    fn problems(files: &[(&str, &str)]) -> Vec<String> {
        check(&tree(files), &roots(&[]), &LAYOUT)
            .1
            .into_iter()
            .collect()
    }

    /// A contract whose table of open obligations has `rows`, followed by
    /// another section with a table.
    fn contract(rows: &[&str]) -> String {
        format!(
            "# Demo\n\n## Open obligations\n\n| Obligation | Kind | Verified state | Carrier | Stage |\n| --- | --- | --- | --- | --- |\n{}\n\n## References\n\n| Not | An | Obligation |\n| --- | --- | --- |\n| a | b | c |\n",
            rows.join("\n")
        )
    }

    /// The open obligations of the contracts in `files`, and their problems.
    fn obligations_of(files: &[(&str, &str)]) -> (Vec<Json>, Vec<String>) {
        let (obligations, problems) = obligations(&Tree::from_files(files), LAYOUT.kernel);
        (obligations, problems.into_iter().collect())
    }

