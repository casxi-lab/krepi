/// The columns and kinds of open obligations, the words of verified states,
/// the latest stage, the release after the one in work, and `open.json`.
const COLUMNS: [&str; 5] = ["Obligation", "Kind", "Verified state", "Carrier", "Stage"];
const KINDS: [&str; 5] = ["code", "unsafe", "assembly", "mmio", "register-state"];
const STATES: [&str; 4] = ["Reads and writes", "Reads", "Writes", "Neither"];
const STAGE_LIMIT: &str = "0.2";
const DESCRIPTION: &str = "Generated by cargo xtask formal check --write from the Open obligations tables of the contracts of the components: the obligations of the production code of the kernel workspace that no proof target closes, each with its carrier and the release by which it is to be closed or lifted. A file that differs from the generated text fails cargo xtask formal check.";

/// The method of the derived implementation of each standard trait.
pub const DERIVED: &str = "Clone:clone Debug:fmt PartialEq:eq Eq:assert_fields_are_eq PartialOrd:partial_cmp Ord:cmp Hash:hash Default:default";

/// A `mod` declaration, after its inline modules, each with its `#[path]`.
type Chain = Vec<(String, Option<String>)>;

/// What a file defines outside function bodies and test code: functions,
/// as `[<inline>::]...[<Owner>::]<name>` with whether they implement a trait,
/// derived methods, file modules with whether they are test code, problems.
#[derive(Debug, Default)]
pub struct Scan {
    functions: Vec<(String, bool)>,
    derived: Vec<String>,
    modules: Vec<(Chain, bool)>,
    problems: Vec<String>,
    inline: Chain,
    owner: Option<(Option<String>, bool)>,
    test: bool,
}

impl Scan {
    fn function(&mut self, attrs: &[Attribute], ident: &Ident) {
        let inline: String = self.inline.iter().map(|m| m.0.clone() + "::").collect();
        let function = match &self.owner {
            _ if self.test || is_test(attrs) => return,
            Some((None, _)) => return self.problems.push(format!("{inline}{ident}: no key")),
            Some((Some(owner), of_trait)) => (format!("{inline}{owner}::{ident}"), *of_trait),
            None => (format!("{inline}{ident}"), false),
        };
        self.functions.push(function);
    }

    fn derives<'a>(&mut self, attrs: &'a [Attribute], ident: &Ident) -> &'a [Attribute] {
        let inline: String = self.inline.iter().map(|m| m.0.clone() + "::").collect();
        let parse = Punctuated::<syn::Path, Token![,]>::parse_terminated;
        let derives = attrs.iter().filter(|attr| attr.path().is_ident("derive"));
        let paths = derives.flat_map(|attr| attr.parse_args_with(parse));
        for path in paths.flatten().filter(|_| !self.test && !is_test(attrs)) {
            let last = path.segments.last().map(|last| format!("{}:", last.ident));
            let mut pairs = DERIVED.split(' ');
            if let Some(method) = pairs.find_map(|pair| pair.strip_prefix(last.as_deref()?)) {
                self.derived.push(format!("{inline}{ident}::{method}"));
            }
        }
        attrs
    }
}

impl<'ast> Visit<'ast> for Scan {
    fn visit_item(&mut self, item: &'ast syn::Item) {
        let attrs: &[Attribute] = match item {
            syn::Item::Fn(item) => return self.function(&item.attrs, &item.sig.ident),
            syn::Item::Struct(item) => self.derives(&item.attrs, &item.ident),
            syn::Item::Enum(item) => self.derives(&item.attrs, &item.ident),
            syn::Item::Union(item) => self.derives(&item.attrs, &item.ident),
            syn::Item::Const(item) => &item.attrs,
            syn::Item::Static(item) => &item.attrs,
            _ => &[],
        };
        if !is_test(attrs) {
            visit::visit_item(self, item);
        }
    }
    fn visit_impl_item_fn(&mut self, item: &'ast syn::ImplItemFn) {
        self.function(&item.attrs, &item.sig.ident);
    }
    fn visit_trait_item_fn(&mut self, item: &'ast syn::TraitItemFn) {
        if item.default.is_some() {
            self.function(&item.attrs, &item.sig.ident);
        }
    }
    fn visit_item_impl(&mut self, item: &'ast syn::ItemImpl) {
        if !is_test(&item.attrs) {
            let owner = (owner(&item.self_ty), item.trait_.is_some());
            let outer = self.owner.replace(owner);
            visit::visit_item_impl(self, item);
            self.owner = outer;
        }
    }
    fn visit_item_trait(&mut self, item: &'ast syn::ItemTrait) {
        if !is_test(&item.attrs) {
            let outer = self.owner.replace((Some(item.ident.to_string()), false));
            visit::visit_item_trait(self, item);
            self.owner = outer;
        }
    }
    fn visit_item_mod(&mut self, item: &'ast syn::ItemMod) {
        let test = self.test || is_test(&item.attrs);
        let module = (item.ident.to_string(), path_of(&item.attrs));
        self.inline.push(module);
        let module = item.content.is_none().then(|| (self.inline.clone(), test));
        self.modules.extend(module);
        let outer = std::mem::replace(&mut self.test, test);
        visit::visit_item_mod(self, item);
        (self.test, _) = (outer, self.inline.pop());
    }
    fn visit_item_macro(&mut self, item: &'ast syn::ItemMacro) {
        let body = TokenBuffer::new2(item.mac.tokens.clone());
        let holds = |at: Cursor| at.ident().is_some_and(|(word, _)| word == "fn");
        let rules = item.mac.path.is_ident("macro_rules") && !self.test && !is_test(&item.attrs);
        if rules && finds(body.begin(), holds) {
            let name = item.ident.as_ref().map_or(String::new(), Ident::to_string);
            self.problems.push(format!("macro {name}: holds fn"));
        }
    }
}

/// Whether `attrs` hold `cfg(test)` in exactly this form.
pub fn is_test(attrs: &[Attribute]) -> bool {
    let test = |attr: &Attribute| attr.parse_args::<Ident>().is_ok_and(|word| word == "test");
    let mut cfgs = attrs.iter().filter(|attr| attr.path().is_ident("cfg"));
    cfgs.any(test)
}

/// The string of the first `#[path]` in `attrs`.
fn path_of(attrs: &[Attribute]) -> Option<String> {
    let attr = attrs.iter().find(|attr| attr.path().is_ident("path"))?;
    let value = &attr.meta.require_name_value().ok()?.value;
    let Expr::Lit(lit) = value else { return None };
    let Lit::Str(s) = &lit.lit else { return None };
    Some(s.value())
}

/// The last path segment of the self type `ty`, under `&`, `*` and `()`.
pub(super) fn owner(ty: &Type) -> Option<String> {
    match ty {
        Type::Path(ty) => Some(ty.path.segments.last()?.ident.to_string()),
        Type::Reference(ty) => owner(&ty.elem),
        Type::Ptr(ty) => owner(&ty.elem),
        Type::Paren(ty) => owner(&ty.elem),
        _ => None,
    }
}

/// Whether `hit` holds at a token from `cursor` on, at any depth.
pub fn finds(cursor: Cursor, hit: fn(Cursor) -> bool) -> bool {
    let mut tokens = std::iter::successors(Some(cursor), |at| Some(at.token_tree()?.1));
    tokens.any(|at| hit(at) || at.any_group().is_some_and(|(group, ..)| finds(group, hit)))
}

/// Scans one file; an error when it does not parse or names `include`, raw
/// or not, which is how any macro call or import reaches `include!`.
pub fn scan(text: &str) -> Result<Scan, String> {
    let include = |at: Cursor| at.ident().is_some_and(|word| word.0.unraw() == "include");
    let parser = |input: ParseStream| Ok((finds(input.cursor(), include), input.parse()?));
    let parsed: syn::Result<(bool, syn::File)> = parser.parse_str(text);
    let (included, file) = parsed.map_err(|error| format!("does not parse: {error}"))?;
    let mut scan = Scan::default();
    scan.visit_file(&file);
    (!included).then_some(scan).ok_or("names include".into())
}

/// The file that `chain` names by the rules of rustc among `files`, from a
/// file at `at`: its directory, for `#[path]`, and that of the modules that it
/// declares, longer by its name unless it is a root, `mod.rs` or `#[path]`.
fn resolve(files: &BTreeMap<&str, Option<Scan>>, at: &(String, String), chain: &Chain) -> Found {
    let ((name, path), inline) = chain.split_last().expect("a declared module");
    let join = |dir: &str, part: &str| repo::join(dir, part).unwrap_or_default();
    let at = inline.iter().fold(at.clone(), |at, (module, path)| {
        let dir = path.as_ref().map(|path| join(&at.0, path));
        let dir = dir.unwrap_or_else(|| join(&at.1, module));
        (dir.clone(), dir)
    });
    let found = |file: String| files.contains_key(file.as_str()).then_some(file);
    let below = format!("{}/{name}", at.1);
    let (flat, nested) = (format!("{below}.rs"), format!("{below}/mod.rs"));
    let file = match (path, found(flat.clone()), found(nested.clone())) {
        (Some(path), ..) => found(join(&at.0, path)).ok_or(format!("mod {name}: no {path:?}"))?,
        (None, Some(file), None) => return Ok((file, (at.1, below))),
        (None, None, Some(file)) => file,
        (None, None, None) => return Err(format!("mod {name}: no file {flat} or {nested}")),
        (None, Some(_), Some(_)) => return Err(format!("mod {name}: both {flat} and {nested}")),
    };
    let dir = repo::parent(&file).to_string();
    Ok((file, (dir.clone(), dir)))
}

type Found = Result<(String, (String, String)), String>;
type Problems = BTreeSet<String>;

/// The reached files, whether production code reaches each, and the keys;
/// and the paths of the modules of each production file below the root of
/// its crate, such as `a::b`, empty for a root.
#[derive(Debug, Default)]
pub struct Inventory {
    pub reached: BTreeMap<String, bool>,
    pub functions: BTreeSet<String>,
    pub derived: BTreeSet<String>,
    pub modules: BTreeMap<String, BTreeSet<String>>,
}

/// The inventory of the `.rs` files that `tree` tracks below `kernel` from the
/// `roots`, each with whether it is a production root; a file that two `mod`
/// declarations load is walked from both.
pub fn inventory(tree: &Tree, roots: &[(String, bool)], kernel: &str) -> (Inventory, Problems) {
    let (mut problems, mut scans) = (BTreeSet::new(), BTreeMap::new());
    let rust = |path: &&str| path.ends_with(".rs") && repo::is_within(path, kernel);
    for (path, _) in tree.entries().filter(|(path, _)| rust(path)) {
        let text = tree.text(path).ok_or("not a UTF-8 regular file".into());
        let scan = text.and_then(scan).map_err(|e| format!("{path}: {e}"));
        problems.extend(scan.as_ref().err().cloned());
        scans.insert(path, scan.ok());
    }
    let mut queue = Vec::new();
    for (root, production) in roots {
        let dir = repo::parent(root).to_string();
        problems.extend((!scans.contains_key(root.as_str())).then(|| format!("{root}: untracked")));
        queue.push((root.clone(), (dir.clone(), dir), *production, String::new()));
    }
    let (mut inventory, mut seen) = (Inventory::default(), BTreeSet::new());
    while let Some((file, at, production, module)) = queue.pop() {
        if !seen.insert((file.clone(), at.clone(), production)) {
            continue;
        }
        *inventory.reached.entry(file.clone()).or_default() |= production;
        let scan = scans.get(file.as_str()).and_then(Option::as_ref);
        for (chain, test) in scan.iter().flat_map(|scan| &scan.modules) {
            let names = chain.iter().map(|(name, _)| name.as_str());
            let below = (module.split("::").filter(|part| !part.is_empty()))
                .chain(names)
                .collect::<Vec<_>>()
                .join("::");
            match resolve(&scans, &at, chain) {
                Ok((file, at)) => queue.push((file, at, production && !test, below)),
                Err(problem) => _ = problems.insert(format!("{file}: {problem}")),
            }
        }
        if production {
            let modules = inventory.modules.entry(file.clone()).or_default();
            modules.insert(module.clone());
        }
        if let Some(scan) = scan.filter(|_| production) {
            problems.extend(scan.problems.iter().map(|p| format!("{file}: {p}")));
            let derived = scan.derived.iter().map(|d| format!("{file}#{d}"));
            inventory.derived.extend(derived);
            for (index, (name, _)) in scan.functions.iter().enumerate() {
                let named = |(other, _): &&(String, bool)| other == name;
                let same: Vec<_> = scan.functions.iter().filter(named).collect();
                let before = scan.functions[..index].iter().filter(named).count();
                let shared = same.len() > 1 && same.iter().any(|(_, of_trait)| !of_trait);
                let key = format!("{file}#{name}");
                problems.extend(shared.then(|| format!("{key}: {} functions", same.len())));
                let number = (before > 0).then(|| format!("#{}", before + 1));
                let key = key + &number.unwrap_or_default();
                inventory.functions.extend((!shared).then_some(key));
            }
        }
    }
    let reached = &inventory.reached;
    let unreached = scans.keys().filter(|file| !reached.contains_key(**file));
    problems.extend(unreached.map(|file| format!("{file}: no mod declaration reaches it")));
    (inventory, problems)
}

/// The roots of the targets of the kernel workspace in `cargo metadata`, as
/// paths below `kernel`, each with whether it is a production root.
pub fn roots(metadata: &Json, kernel: &str) -> Result<Vec<(String, bool)>, String> {
    let workspace = metadata["workspace_root"].as_str().unwrap_or_default();
    let packages = metadata["packages"].as_array().into_iter().flatten();
    let targets = packages.flat_map(|package| package["targets"].as_array().into_iter().flatten());
    let root = |target: &Json| {
        let path = target["src_path"].as_str().unwrap_or_default();
        let below = path.strip_prefix(workspace).filter(|r| r.starts_with('/'));
        let below = below.ok_or(format!("{path:?}: not below {workspace}"))?;
        let kind = target["kind"][0].as_str().unwrap_or_default();
        let production = !["test", "bench", "example", "custom-build"].contains(&kind);
        Ok((format!("{kernel}{below}"), production))
    };
    targets.map(root).collect()
}

/// The entry of `open.json` that the cells of a row of `contract` give.
fn obligation(cells: &[&str], kernel: &str, contract: &str) -> Result<Json, String> {
    let [item, kind, state, carrier, stage, ..] = cells[..] else {
        return Err(format!("{} cells", cells.len()));
    };
    let code = |cell: &str| Some(cell.strip_prefix('`')?.split_once('`')?.0.to_owned());
    let [item, kind] = [item, kind].map(|cell| code(cell).unwrap_or_default());
    let stage = stage.trim_matches('`');
    let leads = |word: &&str| state == *word || state.starts_with(&format!("{word} "));
    let verified_state = STATES.into_iter().find(leads).map(str::to_lowercase);
    let entry = json!({"item": item, "kind": kind, "verified_state": verified_state, "carrier": carrier, "stage": stage, "contract": contract});
    let (blank, file) = (["", "-"], item.split('#').next().unwrap_or_default());
    let column = match () {
        _ if file == kernel || !repo::is_within(file, kernel) => "obligation",
        _ if !KINDS.contains(&kind.as_str()) => "kind",
        _ if verified_state.is_none() && !blank.contains(&state) => "verified state",
        _ if blank.contains(&carrier) => "carrier",
        _ if version(stage).is_none() => "stage",
        _ => return Ok(entry),
    };
    Err(format!("the {column} cell is malformed"))
}

/// The release `MAJOR.MINOR` that `text` names.
fn version(text: &str) -> Option<(u32, u32)> {
    let (major, minor) = text.split_once('.')?;
    let digits = (major.bytes().chain(minor.bytes())).all(|b| b.is_ascii_digit());
    digits.then_some((major.parse().ok()?, minor.parse().ok()?))
}

/// The entries of `open.json` from the `Open obligations` of the contracts.
pub fn obligations(tree: &Tree, kernel: &str) -> (Vec<Json>, Problems) {
    let (mut obligations, mut problems) = (Vec::new(), BTreeSet::new());
    for (path, text) in tree.texts() {
        let parts: Vec<&str> = path.split('/').collect();
        if !matches!(parts[..], ["docs", "domains", _, _, "contract.md"]) {
            continue;
        }
        let mut sections = text.split("\n## ");
        let section = sections.find_map(|s| s.strip_prefix("Open obligations\n"));
        let (lines, mut width) = (section.into_iter().flat_map(str::lines), None);
        for (row, line) in lines.filter(|line| line.starts_with('|')).enumerate() {
            let cells: Vec<&str> = line.trim_matches('|').split('|').map(str::trim).collect();
            let header = *width.get_or_insert(cells.len());
            let entry = match row {
                0 if !cells.starts_with(&COLUMNS) => Err("wrong columns".into()),
                _ if cells.len() != header => Err(format!("{} cells", cells.len())),
                0 | 1 => continue,
                _ => obligation(&cells, kernel, path),
            };
            match entry {
                Ok(entry) => obligations.push(entry),
                Err(problem) => _ = problems.insert(format!("{path}: row {}: {problem}", row + 1)),
            }
        }
    }
    obligations.sort_by(|a, b| a["item"].as_str().cmp(&b["item"].as_str()));
    let pairs = obligations.windows(2);
    let twice = pairs.filter(|pair| pair[0]["item"] == pair[1]["item"]);
    problems.extend(twice.map(|pair| format!("{}: listed twice", pair[0]["item"])));
    (obligations, problems)
}

/// The text of `verification/open.json` for the entries `obligations`.
pub fn open_json(obligations: &[Json]) -> String {
    let open = json!({"schema": 1, "description": DESCRIPTION, "entries": obligations});
    serde_json::to_string_pretty(&open).expect("JSON") + "\n"
}

/// Checks the tracked files of `tree` with the `roots` of the kernel targets.
pub fn check(tree: &Tree, roots: &[(String, bool)], layout: &Layout) -> (String, Problems) {
    let (inventory, mut problems) = inventory(tree, roots, layout.kernel);
    let text = |path: &str| tree.text(path).ok_or(format!("{path} is not tracked"));
    let registries = text(layout.registry).and_then(|t| registry::check(t, text(layout.models)?));
    let (targets, refused) = match registries {
        Ok((registry, refused)) => (registry.targets, refused),
        Err(problem) => (Vec::new(), vec![problem]),
    };
    let axioms = text(layout.axioms).and_then(registry::axiom_rules);
    let axioms = axioms.unwrap_or_else(|problem| vec![problem]);
    problems.extend(
        axioms
            .into_iter()
            .map(|problem| format!("{}: {problem}", layout.axioms)),
    );
    let mut keys = BTreeSet::new();
    for target in &targets {
        let lists = [("proves", &target.proves), ("unclosed", &target.unclosed)];
        for (list, entries) in lists {
            for key in entries {
                keys.insert(key.clone());
                let stale = !inventory.functions.contains(key);
                let name = &target.name;
                problems.extend(
                    stale.then(|| {
                        format!("target {name}: {key} of {list} is no production function")
                    }),
                );
            }
        }
        problems.extend(classify::derived_problems(target, &inventory));
    }
    let (lists, uncovered) = mutants::list_problems(tree, layout, &targets);
    problems.extend(lists);
    // A layout without open obligations reads no contract.
    let (obligations, tables) = match layout.open {
        "" => (Vec::new(), Problems::new()),
        _ => obligations(tree, layout.kernel),
    };
    problems.extend(refused.into_iter().chain(tables));
    let mut items = Vec::new();
    for entry in &obligations {
        let field = |name: &str| entry[name].as_str().unwrap_or_default();
        let (item, stage) = (field("item"), field("stage"));
        let late = version(stage) > version(STAGE_LIMIT);
        problems.extend(late.then(|| format!("{item}: stage {stage}, later than {STAGE_LIMIT}")));
        let silent = field("kind") == "unsafe" && entry["verified_state"].is_null();
        problems.extend(silent.then(|| format!("{item}: unsafe without a verified state")));
        items.push(item);
    }
    if !layout.open.is_empty() && tree.text(layout.open) != Some(open_json(&obligations).as_str()) {
        problems.insert(format!("{}: not what the contracts give", layout.open));
    }
    for key in &inventory.functions {
        let file = key.split('#').next().unwrap_or_default();
        let has = |item: &&str| *item == key || !item.contains('#') && repo::is_within(file, item);
        let open = !keys.contains(key) && !items.iter().any(has);
        problems.extend(open.then(|| format!("{key}: no target and no open obligation")));
    }
    let (files, functions) = (inventory.reached.len(), inventory.functions.len());
    let (derived, open) = (inventory.derived.len(), obligations.len());
    let mut read = format!("{files} files, {functions} functions, {derived} derived, {open} open");
    if !uncovered.is_empty() {
        let uncovered = Vec::from_iter(uncovered).join(", ");
        read.push_str(&format!(
            "; survivors that no theorem covers in {uncovered}"
        ));
    }
    (read, problems)
}

/// The command line of `cargo xtask formal check`, with the text `about`.
pub fn cli(about: &'static str) -> clap::Command {
    let write = Arg::new("write").long("write").action(ArgAction::SetTrue);
    let write = write.help("First write verification/open.json, unless a table is malformed");
    let calibration = clap::arg!(--calibration "Check the calibration target");
    clap::Command::new("check")
        .about(about)
        .args([write, calibration])
}

/// `cargo xtask formal check` in `root`; with `write`, it first writes
/// `open.json` unless a table is malformed. It exits with 1 on any problem.
pub fn command(root: &Path, layout: &Layout, write: bool) -> ExitCode {
    let checked = || -> Result<_, String> {
        let (mut tree, open) = (Tree::load(root)?, root.join(layout.open));
        let (obligations, tables) = obligations(&tree, layout.kernel);
        if write && tables.is_empty() && !layout.open.is_empty() {
            let written = fs::write(&open, open_json(&obligations));
            written.map_err(|error| format!("{}: {error}", open.display()))?;
            tree = Tree::load(root)?;
        }
        let roots = roots(
            &manifests::kernel_metadata(root, layout.kernel)?,
            layout.kernel,
        )?;
        Ok(check(&tree, &roots, layout))
    };
    let (read, problems) = checked().unwrap_or_else(|e| (String::new(), BTreeSet::from([e])));
    for problem in &problems {
        println!("FAILED {problem}");
    }
    println!("{read}; {} problems", problems.len());
    ExitCode::from(u8::from(!problems.is_empty()))
}

